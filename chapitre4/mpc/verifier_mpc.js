'use strict';
const assert=require('node:assert/strict'),fs=require('node:fs'),path=require('node:path'),vm=require('node:vm');
const solver=require('./verifier_solver.js').runVerification();
let uiChecks=0;
const ok=(v,msg)=>{assert.ok(v,msg);uiChecks++};
const html=fs.readFileSync(path.join(__dirname,'index.html'),'utf8');
ok(html.includes(fs.readFileSync(path.join(__dirname,'mpc.js'),'utf8').trim()),'Embedded solver identity');
ok(!/<script[^>]+src=|fetch\(|https?:\/\//i.test(html),'Offline independent HTML');
const elements=new Map();
function element(id){if(!elements.has(id))elements.set(id,{value:'',textContent:'',innerHTML:'',className:'',disabled:false,events:{},addEventListener(t,f){this.events[t]=f;}});return elements.get(id);}
let pending=null;
const context=vm.createContext({document:{getElementById:element},setTimeout:f=>{pending=f;return 1;},clearTimeout:()=>{pending=null;}});
for(const match of html.matchAll(/<script[^>]*>([\s\S]*?)<\/script>/g))vm.runInContext(match[1],context);
const click=id=>element(id).events.click();
const change=(id,value)=>{element(id).value=String(value);element(id).events.change();};
const number=id=>Number(element(id).textContent.replace(',','.'));
const near=(a,b,t=1e-7)=>ok(Math.abs(a-b)<=t,`${a} != ${b}`);
near(number('mx'),0);near(number('ma'),-1);
click('step');near(number('mx'),1.5);click('step');near(number('mx'),2);near(number('mv'),0);
ok(element('step').disabled&&element('status').innerHTML.includes('Arrêt obtenu'),'Default stop');
change('horizon',1);near(number('mx'),0);near(number('ma'),0);click('step');
ok(element('status').innerHTML.includes('infaisable')&&element('step').disabled,'N1 infeasible');
click('preset-far');ok(element('horizon').value==='3'&&element('initial-speed').value==='4'&&element('line-distance').value==='8','Faster preset');
for(let k=0;k<4;k++)click('step');near(number('mx'),8);near(number('mv'),0);ok(element('step').disabled,'N3 stops');
change('horizon',2);near(number('ma'),0);click('step');ok(element('status').innerHTML.includes('infaisable'),'Faster N2 fails');
click('preset-course');change('horizon',20);ok((element('plan').innerHTML.match(/<tr>/g)||[]).length===20,'20 rows');
change('initial-speed',1.5);ok(element('braking-distance').textContent.includes('1,25'),'Sampled stopping distance');
change('line-distance',0.5);ok(element('status').innerHTML.includes('infaisable'),'Initially impossible');
change('line-distance',20);change('initial-speed',5);change('rho',10);near(number('mx'),0);ok(!element('step').disabled,'Extreme feasible controls');
ok(element('desired-speed').textContent.includes('5,0')&&element('costformula').textContent.includes('10 aᵢ²'),'Cost reflects controls');
click('play');ok(element('play').textContent==='Pause'&&pending,'Playback schedules');const tick=pending;tick();ok(number('mx')>0,'Playback advances');click('play');ok(element('play').textContent==='Lire'&&!pending,'Pause cancels');
click('reset');near(number('mx'),0);
click('preset-far');change('line-distance',12);change('horizon',4);
let steps=0;while(!element('step').disabled&&steps++<120)click('step');
ok(element('status').innerHTML.includes('Quasi-arrêt avant la ligne')&&number('mx')<12,'Stationary point before line');
click('preset-course');context.MPC.solve=()=>({status:'numerical_failure',u:null,states:[]});click('reset');
ok(element('status').innerHTML.includes('commande validée')&&element('step').disabled&&element('play').disabled,'Numerical failure distinct');
ok(!element('plan').innerHTML.includes('maintenant'),'No stale command on failure');
console.log(JSON.stringify({status:'passed',solver,uiChecks,notes:'Actual UI handlers exercised in a minimal DOM; rendering requires browser inspection.'},null,2));
